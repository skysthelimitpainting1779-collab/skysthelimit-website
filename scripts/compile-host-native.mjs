function cursorRule(a) {
  const globs = (a.allow_globs || []).join(', ');
  return `---
description: Specialist ${a.id} — auto when matching paths
globs: "${globs}"
alwaysApply: false
---

# ${a.name} (${a.id})

${a.description}

${a.prompt}

**Allow writes:** ${globs || 'n/a'}

**Deny:** ${(a.deny_globs || []).join(', ') || 'n/a'}

Prefer this specialist's jurisdiction. Root kernel: AGENTS.md.
`;
}

function stripFrontmatter(source) {
  return source.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').trim();
}

function escapeTomlMultiline(source) {
  return source.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"');
}

function codexToml({ id, description, instructions, readOnly = false }) {
  const esc = escapeTomlMultiline(instructions);
  return `# AUTO-GENERATED by npm run host:compile — edit .agents/specialists.json
name = ${JSON.stringify(id)}
description = ${JSON.stringify(description)}
${readOnly ? 'sandbox_mode = "read-only"\n' : ''}developer_instructions = """
${esc}
"""
`;
}

function codexAgent(a, antigravitySource) {
  const roleMode = a.id === 'A0'
    ? 'The primary Codex thread is A0. This A0 profile is for explicit root-orchestrator selection and must not be spawned as a child.'
    : `You are ${a.id}, a bounded standing agent dispatched by A0. Report coordination and scope conflicts to A0.`;
  const instructions = [
    roleMode,
    'Inherit the repository AGENTS.md and .agents/KERNEL.md. Those upstream constraints override this domain profile.',
    'Use Graphify before code discovery and Context7 only when current external-library behavior materially affects the task.',
    'Load only matching skills from .agents/skills/. Preserve exact-head evidence, bounded remediation, and human production gates.',
    '',
    stripFrontmatter(antigravitySource),
  ].join('\n');

  return codexToml({
    id: a.id,
    description: a.description,
    instructions,
    readOnly: ['A1', 'A6', 'A10'].includes(a.id),
  });
}

function verifierManifest(id) {
  const dir = join(ROOT, '.agents', 'manifests', 'verifiers');
  const filename = readdirSync(dir).find((file) => file.startsWith(`${id}-`) && file.endsWith('.json'));
  if (!filename) throw new Error(`Missing canonical verifier manifest for ${id}`);
  return JSON.parse(readFileSync(join(dir, filename), 'utf8'));
}

function codexVerifier(id) {
  const sourcePath = join(ROOT, '.agents', 'agents', `${id.toLowerCase()}.md`);
  if (!existsSync(sourcePath)) throw new Error(`Missing canonical verifier prompt ${sourcePath}`);
  const manifest = verifierManifest(id);
  const instructions = [
    `You are ${id}, the clean-context independent verifier for A${id.slice(1)}.`,
    'Operate read-only. Parent conversation history is prohibited and must not be provided.',
    'Receive only the task contract, base SHA, candidate SHA, exact diff, acceptance criteria, Graphify blast radius, relevant Context7 evidence, and reproducible test or preview evidence.',
    'Return exactly PASS, FAIL, or UNCERTAIN. FAIL and UNCERTAIN block completion. Never repair a finding or give collaborative implementation hints.',
    '',
    stripFrontmatter(readFileSync(sourcePath, 'utf8')),
  ].join('\n');

  return codexToml({
    id,
    description: manifest.mission ?? manifest.identity?.role ?? `${id} independent verifier`,
    instructions,
    readOnly: true,
  });
}

function codexSpecialist(specialist) {
  const instructions = [
    `You are ${specialist.id}, a narrow diagnostic specialist owned by ${specialist.parent}.`,
    `Mission: ${specialist.mission}`,
    'You are strictly read-only and cannot spawn or invoke subagents.',
    `You may message only ${specialist.parent}; report only to that parent with evidence, unknowns, and no implementation edits.`,
    'Inherit AGENTS.md and .agents/KERNEL.md. Use Graphify for code discovery and Context7 only for version-sensitive external APIs.',
  ].join('\n');

  return codexToml({
    id: specialist.id,
    description: `${specialist.name}: ${specialist.mission}`,
    instructions,
    readOnly: true,
  });
}

function mirrorSkills() {
  const written = [];
  if (!existsSync(SKILLS_SSOT)) return written;
  const targets = [
    join(ROOT, '.claude', 'skills'),
    join(ROOT, '.github', 'skills'),
  ];
  for (const t of targets) {
    ensureDir(t);
  }
  for (const name of readdirSync(SKILLS_SSOT, { withFileTypes: true })) {
    if (!name.isDirectory()) continue;
    const src = join(SKILLS_SSOT, name.name);
    if (!existsSync(join(src, 'SKILL.md'))) continue;
    for (const t of targets) {
      const dest = join(t, name.name);
      if (existsSync(dest)) rmSync(dest, { recursive: true, force: true });
      cpSync(src, dest, { recursive: true });
      written.push(dest.replace(ROOT + '\\', '').replace(ROOT + '/', ''));
    }
  }
  return written;
}

